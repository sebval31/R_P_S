private Partida partida = new Partida();
private Random azar = new Random();

private void jugar(Jugada elegida) {
    int numero = azar.nextInt(3);
    Jugada pc = Jugada.values()[numero];

    partida.jugarRonda(elegida, pc);

    Rival.setText("Contrincante: " + pc);
    Puntos.setText("Puntos: Tú " + partida.getWinj1() + " - PC " + partida.getWinj2());

    String quienGana = partida.obtenerGanador();
    String texto;

    if (quienGana.equals("Player 1")) {
        texto = "Tú";
    } else if (quienGana.equals("Player 2")) {
        texto = "PC";
    } else {
        texto = "Empate";
    }

    Resultado.setText("Resultado: " + texto);
}
